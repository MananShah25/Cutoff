std::string embedded_source(const GenerateResult& r) {
  std::ostringstream os;
  os << "// GENERATED by cutoff-mutgen. DO NOT EDIT.\n"
     << "#include <string_view>\n\nnamespace cutoff::detail {\n\n"
     << "extern const std::string_view kDrillManifest;\nextern const std::string_view kDrillSummary;\nextern const int kDrillMutants;\n\n"
     << "const std::string_view kDrillManifest = R\"CUTOFFMANIFEST(" << r.manifest << ")CUTOFFMANIFEST\";\n"
     << "const std::string_view kDrillSummary = R\"CUTOFFMANIFEST(" << describe(r) << ")CUTOFFMANIFEST\";\n"
     << "const int kDrillMutants = " << r.mutants.size() << ";\n\n}  // namespace cutoff::detail\n";
  return os.str();
}

